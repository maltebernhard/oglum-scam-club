// Generates web/src/seed.js from pwa/data/locations.json (+ the legacy Köln/Düsseldorf list).
// Usage: node pwa/tools/gen-seed.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = JSON.parse(fs.readFileSync(path.join(root, 'data', 'locations.json'), 'utf8').replace(/^\uFEFF/, ''))
const legacy = JSON.parse(fs.readFileSync(path.join(root, 'web', 'data', 'legacy-koeln-duesseldorf.json'), 'utf8'))

const TYPE_TO_CATEGORY = {
  GYM: 'Fitness',
  YOGA_STUDIO: 'Yoga',
  OUTDOOR: 'Outdoor',
  SWIMMING_POOL: 'Water Sports',
  WATER_SPORT: 'Water Sports',
  DANCE: 'Dance',
  EMS_STUDIO: 'EMS',
  MARTIAL_ARTS: 'Martial Arts',
  WELLNESS: 'Wellness',
  PILATES: 'Pilates',
  RACKET: 'Racket',
  BALL_SPORT: 'Other',
  OTHERS: 'Other',
  GOLF: 'Other',
  CYCLING: 'Cycling',
  PHYSIO: 'Physio',
  CROSSFIT: 'CrossFit',
  BOULDER_HALL: 'Bouldering',
  FEVERDREAM: 'Fever Dream',
}

const fold = (value) => String(value).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
const makeID = (name) => fold(name).replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
const round5 = (n) => Math.round(n * 1e5) / 1e5

const fresh = source.locations
  .map((l) => {
    const category = TYPE_TO_CATEGORY[l.studioType]
    if (!category) throw new Error(`Unmapped studioType ${l.studioType} (${l.name})`)
    const lat = l.coordinates?.latitude
    const lng = l.coordinates?.longitude
    const row = [l.name.trim(), category, (l.address?.city ?? '').trim()]
    if (Number.isFinite(lat) && Number.isFinite(lng)) row.push(round5(lat), round5(lng))
    return row
  })
  .sort((a, b) => a[0].localeCompare(b[0], 'de'))

const rows = [...fresh, ...legacy]

const seen = new Map()
for (const row of rows) {
  const id = makeID(row[0])
  if (!id) throw new Error(`Empty id for ${row[0]}`)
  if (seen.has(id)) throw new Error(`Id collision "${id}": ${seen.get(id)} / ${row[0]}`)
  seen.set(id, row[0])
}

const count = (key) => rows.reduce((acc, row) => ((acc[row[key]] = (acc[row[key]] ?? 0) + 1), acc), {})
const cities = count(2)
const categories = count(1)
const berlin = cities.Berlin ?? 0
const withCoords = rows.filter((row) => row.length === 5).length

const header = `// ${rows.length} WellPass partner studios — ${fresh.length} from the Wellpass finder export (Berlin + Brandenburg), ${legacy.length} legacy Köln/Düsseldorf.
// Generated by pwa/tools/gen-seed.mjs — do not edit by hand.
// Tuple: [name, category, city, lat?, lng?]. Köln/Düsseldorf have no coordinates.
import { normalize, fold } from './categories.js'

export function makeID(name) {
  const slug = fold(name)
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return slug || cryptoId()
}

export function initials(name) {
  return String(name ?? '')
    .trim()
    .split(/\\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((word) => word[0])
    .join('')
    .toUpperCase()
}

export function cryptoId() {
  if (globalThis.crypto?.randomUUID) return globalThis.crypto.randomUUID()
  return \`id-\${Date.now().toString(36)}-\${Math.random().toString(36).slice(2, 10)}\`
}

const SEED = [
`

const footer = `]

export const seed = SEED.map(([name, category, city, lat, lng]) => ({
  id: makeID(name),
  name,
  category: normalize(category),
  city,
  ...(lat !== undefined ? { lat, lng } : {}),
  isCustom: false,
}))
`

const body = rows.map((row) => '  ' + JSON.stringify(row)).join(',\n')
fs.writeFileSync(path.join(root, 'web', 'src', 'seed.js'), header + body + '\n' + footer)

console.log({ total: rows.length, fresh: fresh.length, legacy: legacy.length, berlin, withCoords })
console.log('cities', cities['Köln'], cities['Düsseldorf'], cities['Potsdam'])
console.log('categories', categories)
